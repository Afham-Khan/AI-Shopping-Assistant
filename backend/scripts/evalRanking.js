// Recommendation relevance evaluation (golden set).
//
//   npm run ai:eval                 -> runs every query in api/modules/ai/training/data/ranking-eval.json,
//                                      prints a table + metrics and writes test/RANKING_EVAL.md
//   npm run ai:eval -- --baseline   -> also saves this run as the BEFORE snapshot (test/fixtures/ranking-eval-baseline.json)
//   npm run ai:eval -- --only=dress -> runs only queries whose id or text contains "dress" (no report written)
//   npm run ai:eval -- --failures   -> prints only the failing queries
//   npm run ai:eval -- --tfidf      -> evaluates the TF-IDF fallback (what runs if the neural model is unavailable)
//
// Queries go through the same dialogue manager the chat uses (no HTTP), offline (no LLM rewording).
process.env.LLM_PROVIDER = 'none';
// --tfidf evaluates the fallback ranking used when the neural model is unavailable (no report written)
if (process.argv.includes('--tfidf')) process.env.AI_EMBEDDINGS = 'tfidf';
require('dotenv').config({ quiet: true });
const fs = require('fs');
const path = require('path');
const db = require('../api/db/connection');
const { respond } = require('../api/modules/ai/engine/dialogue/manager');
const { getCatalog } = require('../api/modules/ai/engine/retrieval/catalog');
const { runEval, loadQueries } = require('../api/modules/ai/training/rankingEval');

const ROOT = path.join(__dirname, '..');
const BASELINE = path.join(ROOT, 'test/fixtures/ranking-eval-baseline.json');
const REPORT = path.join(ROOT, 'test/RANKING_EVAL.md');

const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}`));
const only = arg('only')?.split('=')[1]?.toLowerCase();
const failuresOnly = Boolean(arg('failures'));

const pct = (x) => `${(x * 100).toFixed(1)}%`;
const num = (x) => (x == null ? '—' : x.toFixed(3));
const cut = (s, n) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

const metricRows = (s) => [
  ['Queries', s.queries],
  ['Pass rate', `${pct(s.passRate)} (${s.passed}/${s.queries})`],
  ['Precision@3', num(s.precisionAt3)],
  ['nDCG@5', num(s.ndcgAt5)],
  ['Hard-constraint violations in top 3', `${s.violations}${Object.keys(s.violationsByType).length ? ` (${Object.entries(s.violationsByType).map(([k, v]) => `${k} ${v}`).join(', ')})` : ''}`],
  ['Replies whose top pick != first card', s.inconsistentReplies],
  ['Unexpected failures (not marked knownFailure)', s.unexpectedFailures ? s.unexpectedFailures.length : s.queries - s.passed],
];

const printTable = (results) => {
  for (const r of results) {
    if (failuresOnly && r.pass) continue;
    const mark = r.pass ? 'PASS' : r.knownFailure ? 'KNOWN' : 'FAIL';
    console.log(`${mark}  ${cut(r.q, 38).padEnd(38)}  ${cut(r.top3.join(' | ') || '(no products)', 90)}`);
    if (!r.pass) console.log(`      -> ${r.reasons.join('; ')}`);
  }
};

const mdEscape = (s) => String(s).replace(/\|/g, '\\|');

const writeReport = (current, baseline) => {
  const s = current.summary;
  const b = baseline?.summary;
  const lines = [
    '# Recommendation relevance — golden-set evaluation',
    '',
    `Generated by \`npm run ai:eval\` on ${new Date().toISOString().slice(0, 10)} (${s.queries} queries, embeddings mode: ${current.mode}).`,
    'Queries and expectations live in `api/modules/ai/training/data/ranking-eval.json`; how to add one is in `docs/AI_TRAINING.md`.',
    '',
    '## Metrics',
    '',
    b ? '| Metric | BEFORE | AFTER |' : '| Metric | Value |',
    b ? '| --- | --- | --- |' : '| --- | --- |',
  ];
  const now = metricRows(s);
  const before = b ? metricRows(b) : null;
  now.forEach(([k, v], i) => lines.push(b ? `| ${k} | ${before[i][1]} | ${v} |` : `| ${k} | ${v} |`));
  if (b) lines.push('', `BEFORE = snapshot of the original ranking taken ${baseline.takenAt?.slice(0, 10) || ''} on the same queries and judge (${b.queries} queries). Re-save it with \`npm run ai:eval -- --baseline\` only when you want a new starting point.`);
  lines.push(
    '',
    '**How to read it**',
    '- *Pass rate*: share of queries whose top 3 had enough relevant cards, no avoidable constraint violation and a reply that describes the first card.',
    '- *Precision@3*: relevant cards in the top 3, divided by what the catalogue could offer (max 3).',
    '- *nDCG@5*: order quality of the first 5 cards (1.0 = best possible order). Relevance: 2 = meets every expectation, 1 = right constraints but weaker match (e.g. only a secondary colour), 0 = violates a constraint.',
    '- *Violations*: wrong category / gender / budget / brand / colour, or a "must not" word (e.g. heels for running), counted only when the catalogue had a compliant product for that slot.',
    '',
    '## Per query',
    '',
    '| Result | Query | Top 3 | Why |',
    '| --- | --- | --- | --- |',
  );
  for (const r of current.results) {
    lines.push(`| ${r.pass ? 'PASS' : r.knownFailure ? 'FAIL (known)' : '**FAIL**'} | ${mdEscape(r.q)} | ${mdEscape(r.top3.join(' · ') || '(no products)')} | ${mdEscape(r.pass ? `${r.hits3}/${Math.min(3, r.availRelevant)} relevant` : r.reasons.join('; '))} |`);
  }
  if (baseline?.results) {
    const prev = new Map(baseline.results.map((r) => [r.id, r]));
    const fixed = current.results.filter((r) => r.pass && prev.get(r.id) && !prev.get(r.id).pass);
    const broke = current.results.filter((r) => !r.pass && prev.get(r.id)?.pass);
    lines.push('', '## Changes since BEFORE', '');
    lines.push(`Fixed (${fixed.length}): ${fixed.map((r) => `"${r.q}"`).join(', ') || 'none'}`, '');
    lines.push(`Regressed (${broke.length}): ${broke.map((r) => `"${r.q}"`).join(', ') || 'none'}`);
  }
  fs.writeFileSync(REPORT, `${lines.join('\n')}\n`);
};

const main = async () => {
  let queries = loadQueries();
  if (only) queries = queries.filter((q) => q.id.toLowerCase().includes(only) || q.q.toLowerCase().includes(only));
  const started = Date.now();
  const current = await runEval({ respond, getCatalog, queries });
  printTable(current.results);
  console.log('');
  for (const [k, v] of metricRows(current.summary)) console.log(`${k.padEnd(40)} ${v}`);
  console.log(`(${((Date.now() - started) / 1000).toFixed(1)}s, embeddings: ${current.mode})`);
  if (only || process.argv.includes('--tfidf')) return;
  const snapshot = { takenAt: new Date().toISOString(), mode: current.mode, summary: current.summary, results: current.results };
  if (arg('baseline')) {
    fs.mkdirSync(path.dirname(BASELINE), { recursive: true });
    fs.writeFileSync(BASELINE, `${JSON.stringify(snapshot, null, 1)}\n`);
    console.log(`Saved BEFORE snapshot -> ${path.relative(ROOT, BASELINE)}`);
  }
  const baseline = fs.existsSync(BASELINE) ? JSON.parse(fs.readFileSync(BASELINE, 'utf8')) : null;
  writeReport(current, arg('baseline') ? null : baseline);
  console.log(`Report -> ${path.relative(ROOT, REPORT)}`);
};

main()
  .catch((error) => {
    console.error('ai:eval failed:', error);
    process.exitCode = 1;
  })
  .finally(() => db.destroy());
