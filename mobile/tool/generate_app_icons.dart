// Renders the Zelora launcher icons, favicon and PWA icons from the same
// painter the app uses (`ZeloraMarkPainter` in lib/core/widgets/app_logo.dart),
// so the store icon, the Chrome tab and the in-app logo never drift apart.
//
// Run from mobile/ (no extra dependencies — it uses Flutter's own renderer):
//
//   flutter test tool/generate_app_icons.dart
//
// Optional: set ZELORA_ICON_PREVIEW=<dir> to also write a few large preview
// PNGs there for review.
//
// Outputs
//   web/favicon.png                         64 px
//   web/icons/Icon-192.png, Icon-512.png    rounded tile on transparent
//   web/icons/Icon-maskable-192/512.png     full-bleed, glyph in the safe zone
//   web/icons/apple-touch-icon.png          180 px full-bleed (iOS rounds it)
//   android/.../mipmap-*/ic_launcher.png            legacy launcher icons
//   android/.../mipmap-*/ic_launcher_foreground.png adaptive foreground (108 dp)
//   android/.../mipmap-anydpi-v26/ic_launcher.xml   adaptive icon definition
//   android/.../values/ic_launcher_background.xml   adaptive background color
import 'dart:io';
import 'dart:ui' as ui;

import 'package:cartwise/core/theme/app_colors.dart';
import 'package:cartwise/core/widgets/ai_mascot.dart';
import 'package:cartwise/core/widgets/app_logo.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:material_ui/material_ui.dart';

Future<void> _render(String path, int px, CustomPainter painter, {double margin = 0}) async {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  final inset = px * margin;
  canvas.translate(inset, inset);
  painter.paint(canvas, Size.square(px - inset * 2));
  final image = await recorder.endRecording().toImage(px, px);
  final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
  final file = File(path);
  file.parent.createSync(recursive: true);
  file.writeAsBytesSync(bytes!.buffer.asUint8List());
  // ignore: avoid_print
  print('wrote $path (${px}px)');
}

void main() {
  testWidgets('generate Zelora icons', (tester) async {
    await tester.runAsync(() async {
      const tile = ZeloraMarkPainter();
      const tileNoSpark = tile;
      const maskable = ZeloraMarkPainter(fullBleed: true, glyphScale: 0.78);
      const apple = ZeloraMarkPainter(fullBleed: true, glyphScale: 0.9);
      const foreground = ZeloraMarkPainter(tile: null, glyphScale: 0.68);

      // web
      await _render('web/favicon.png', 64, tileNoSpark);
      await _render('web/icons/Icon-192.png', 192, tile, margin: 0.03);
      await _render('web/icons/Icon-512.png', 512, tile, margin: 0.03);
      await _render('web/icons/Icon-maskable-192.png', 192, maskable);
      await _render('web/icons/Icon-maskable-512.png', 512, maskable);
      await _render('web/icons/apple-touch-icon.png', 180, apple);

      // android: legacy (pre-O) launcher icons, with the platform's margin
      const res = 'android/app/src/main/res';
      const densities = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0};
      for (final e in densities.entries) {
        final legacy = (48 * e.value).round();
        await _render('$res/mipmap-${e.key}/ic_launcher.png', legacy, legacy >= 72 ? tile : tileNoSpark, margin: 1 / 24);
        await _render('$res/mipmap-${e.key}/ic_launcher_foreground.png', (108 * e.value).round(), foreground);
      }

      // android: adaptive icon (O+), themed icon uses the same foreground
      File('$res/mipmap-anydpi-v26/ic_launcher.xml')
        ..parent.createSync(recursive: true)
        ..writeAsStringSync('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icons.dart -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
''');
      final hex = AppColors.blue.toARGB32().toRadixString(16).padLeft(8, '0').substring(2).toUpperCase();
      File('$res/values/ic_launcher_background.xml').writeAsStringSync('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icons.dart -->
<resources>
    <color name="ic_launcher_background">#$hex</color>
</resources>
''');

      final preview = Platform.environment['ZELORA_ICON_PREVIEW'];
      if (preview != null && preview.isNotEmpty) {
        await _render('$preview/mark-512.png', 512, tile);
        await _render('$preview/mark-maskable-512.png', 512, maskable);
        await _render('$preview/mark-16.png', 16, tileNoSpark);
        await _render('$preview/mark-32.png', 32, tileNoSpark);
        await _render('$preview/mark-48.png', 48, tileNoSpark);
        await _render('$preview/mark-white-512.png', 512, const ZeloraMarkPainter(tile: Colors.white, glyph: AppColors.blue));
        // the assistant mascot, every mood, big and at icon sizes
        for (final mood in AiMood.values) {
          await _render('$preview/mascot-${mood.name}-256.png', 256, AiMascotPainter(bag: AppColors.blue, eyes: Colors.white, mood: mood, t: 0.3));
        }
        for (final px in [16, 20, 24]) {
          await _render('$preview/mascot-$px.png', px, const AiMascotPainter(bag: AppColors.blue, eyes: Colors.white, simplified: true));
        }
      }
    });
  });
}
